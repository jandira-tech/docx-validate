const selections = [
    {},
    { quick: true },
    { checks: ["relationships"] },
    { checks: ["relationships", "word-markup-compatibility"] },
] as const;
const errorKeys = (result: ValidationResult): string[] =>
    result.issues.filter((issue) => issue.severity === "error").map((issue) => `${issue.code}@${issue.path ?? ""}`);
const ordinary = (result: ValidationResult): void => {
    expect(result.issues.filter((issue) => issue.code === "check-crashed")).toEqual([]);
};
const resolved = async (input: string, profile: Profile, selection = {}): Promise<Awaited<ReturnType<typeof validate>>> => {
    const promise = validate(input, { profile, ...selection });
    await expect(promise).resolves.toHaveProperty("valid");
    const result = await promise;
    ordinary(result);
    return result;
};

const relsCases = [PACKAGE_RELS, DOCUMENT_RELS].flatMap((part) => ROOT_MCE_SHAPES.map((shape) => ({ part, shape })));
describe("invalid root unwrapping (#640)", { timeout: 120_000 }, () => {
    it.each(relsCases)("$part $shape: packed and directory profiles and selections", async ({ part, shape }) => {
        await withTempDir(async (dir) => {
            const parts = rootMceRelationshipsParts(part, shape);
            const bytes = await buildDocx(parts);
            const file = path.join(dir, "root.docx");
            const directory = path.join(dir, "directory.docx");
            writeFileSync(file, bytes);
            for (const [name, xml] of Object.entries(parts)) {
                mkdirSync(path.dirname(path.join(directory, name)), { recursive: true });
                writeFileSync(path.join(directory, name), xml);
            }
            for (const input of [file, directory]) {
                const full = await resolved(input, "word-valid");
                for (const selection of selections) {
                    const result = Object.keys(selection).length ? await resolved(input, "word-valid", selection) : full;
                    expect(result.valid).toBe(false);
                    expect(result.issues).toContainEqual(
                        expect.objectContaining({
                            code: "opc-relationships-structure",
                            path: part,
                            severity: "error",
                        }),
                    );
                    if (!("checks" in selection) || selection.checks.length > 1) {
                        expect(result.issues).toContainEqual(expect.objectContaining({ code: "mce-malformed", path: part }));
                    }
                    expect(errorKeys(full)).toEqual(expect.arrayContaining(errorKeys(result)));
                }
                const strict = await resolved(input, "strict");
                expect(strict.valid).toBe(false);
                expect(strict.issues).toContainEqual(
                    expect.objectContaining({
                        code: "opc-relationships-structure",
                        path: part,
                        severity: "error",
                    }),
                );
                const lenient = await resolved(input, "lenient");
                expect({ valid: lenient.valid, issues: lenient.issues }).toEqual(lenientBefore(part, shape));
                for (const selection of [{ quick: true }, { checks: ["xml-syntax"] }]) {
                    const partial = await resolved(input, "lenient", selection);
                    expect({ valid: partial.valid, issues: partial.issues }).toEqual({ valid: true, issues: [] });
                }
            }
            expect(readFileSync(file)).toEqual(bytes);
            for (const [name, xml] of Object.entries(parts)) expect(readFileSync(path.join(directory, name), "utf8")).toBe(xml);
        });
    });

    it.each(["word/document.xml", "word/styles.xml"].flatMap((part) => ROOT_MCE_SHAPES.map((shape) => ({ part, shape }))))(
        "$part $shape: Word rules return findings and lenient retains its output",
        async ({ part, shape }) => {
            await withTempDir(async (dir) => {
                const file = path.join(dir, "root.docx");
                writeFileSync(
                    file,
                    await buildDocx({
                        ...MINIMAL_PARTS,
                        [part]: rootMceXml(shape, MINIMAL_PARTS[part]!.replace(/<\?xml[^>]*>\n?/, "").repeat(2)),
                    }),
                );
                for (const profile of ["word-valid", "strict"] as const) {
                    const result = await resolved(file, profile);
                    expect(result.valid).toBe(false);
                    expect(result.issues).toContainEqual(expect.objectContaining({ code: "mce-malformed", path: part, severity: "error" }));
                    if (part === "word/document.xml")
                        expect(result.issues).toContainEqual(
                            expect.objectContaining({
                                code: "word-document-root",
                                path: part,
                                severity: "error",
                            }),
                        );
                }
                const full = await resolved(file, "word-valid");
                for (const selection of [{ quick: true }, { checks: ["word-markup-compatibility", "word-document-root"] }]) {
                    const result = await resolved(file, "word-valid", selection);
                    expect(result.valid).toBe(false);
                    expect(errorKeys(full)).toEqual(expect.arrayContaining(errorKeys(result)));
                }
                const lenient = await resolved(file, "lenient");
                expect({ valid: lenient.valid, issues: lenient.issues }).toEqual(lenientBefore(part, shape));
            });
        },
    );

    it.each(ROOT_MCE_SHAPES)("PPTX %s resolves in every profile and legal selection", async (shape) => {
        await withTempDir(async (dir) => {
            const file = path.join(dir, "root.pptx");
            const part = "ppt/_rels/presentation.xml.rels";
            const contents = MINIMAL_PPTX_PARTS[part]!.replace(/^[\s\S]*?<Relationships[^>]*>/, "").replace("</Relationships>", "");
            writeFileSync(
                file,
                await buildPptx({
                    ...MINIMAL_PPTX_PARTS,
                    [part]: rootMceXml(
                        shape,
                        contents.replaceAll(
                            "<Relationship ",
                            '<Relationship xmlns="http://schemas.openxmlformats.org/package/2006/relationships" ',
                        ),
                    ),
                }),
            );
            for (const profile of ["word-valid", "strict", "lenient"] as const) {
                const result = await resolved(file, profile);
                if (profile === "lenient") {
                    expect({ valid: result.valid, issues: result.issues }).toEqual(PPTX_LENIENT[shape]);
                } else {
                    expect(result.valid, profile).toBe(false);
                }
                for (const selection of [{ quick: true }, { checks: ["xml-syntax"] }]) {
                    if (profile !== "strict") await resolved(file, profile, selection);
                }
            }
        });
    });
});

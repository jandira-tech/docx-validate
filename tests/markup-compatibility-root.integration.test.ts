/** #640: Word 16.115 offered recovery for the `_rels/.rels` Fallback shape (session 36, s36c); the other root wrappers are unobserved. Retain the stored-root verdict. */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { withTempDir } from "../src/lib/run-cli";
import type { Profile, ValidationResult } from "../src/lib/types";
import { validate } from "../src/scripts/office/validate";
import { buildDocx, MINIMAL_PARTS } from "./support/minimal-docx";
import { buildPptx, MINIMAL_PPTX_PARTS } from "./support/minimal-pptx";
import {
    DOCUMENT_RELS,
    PACKAGE_RELS,
    ROOT_MCE_SHAPES,
    rootMceXml,
    rootMceRelationshipsParts,
} from "./support/relationships-markup-compatibility-specimens";

// Captured from dd5a3da2 before the fix; preserve every issue field and its order.
const lenientBefore = (part: string, shape: string): ValidationResult => {
    const issues: ValidationResult["issues"] = [
        {
            severity: "info",
            code: "latent-styles-missing",
            path: "word/styles.xml",
            message:
                "word/styles.xml has no <w:latentStyles> block. This is unusual for Word-generated files and indicates the repairer may have regenerated styles from scratch.",
        },
    ];
    const relationships = part.endsWith(".rels");
    if (relationships)
        issues.push({
            severity: "info",
            code: "rel-ids-sequential",
            path: part,
            message: `Relationship Id values in ${part} are sequential from rId1 (likely regenerated by the repairer).`,
        });
    if (shape === "choice" && part !== PACKAGE_RELS) {
        if (part === "word/document.xml") {
            issues.push({
                severity: "error",
                code: "mce-main-root-ignored",
                path: part,
                message: "Required main document part word/document.xml has no root after markup compatibility processing.",
            });
            return { valid: false, issues };
        }
        issues.push({
            severity: "info",
            code: "mce-root-ignored",
            path: part,
            message:
                "Root element mc:AlternateContent is in an ignorable namespace that is not understood; the part has no content to schema-validate.",
        });
        return { valid: true, issues };
    }
    issues.push({ severity: "error", code: "xsd-summary", path: part, message: `${part}: 1 new error(s)` });
    const engineMessage =
        part === PACKAGE_RELS
            ? `Element '${shape === "process-content" ? "{urn:x}Wrap" : "{http://schemas.openxmlformats.org/markup-compatibility/2006}AlternateContent"}': No matching global declaration available for the validation root.`
            : "Only one element can be added and only after doctype";
    issues.push({ severity: "error", code: "xsd-error", path: part, message: `  - ${engineMessage}` });
    return { valid: false, issues };
};

